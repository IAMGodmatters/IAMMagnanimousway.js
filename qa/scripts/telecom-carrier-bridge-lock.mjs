import fs from 'node:fs';

const read=(path)=>fs.readFileSync(path,'utf8');
const main=read('telecom-core/control-api/app/main.py');
const container=read('telecom-core/control-api/app/container.py');
const ports=read('telecom-core/control-api/app/ports.py');
const adapter=read('telecom-core/control-api/app/adapters/asterisk.py');
const calls=read('telecom-core/control-api/app/services/calls.py');
const monitoring=read('telecom-core/control-api/app/services/monitoring.py');
const entrypoint=read('telecom-core/asterisk/entrypoint.sh');
const dialplan=read('telecom-core/asterisk/templates/extensions.conf.template');
const trunk=read('telecom-core/asterisk/templates/pjsip-trunk.conf.optional');
const compose=read('telecom-core/docker-compose.yml');
const phoneCarrier=read('worker/src/phone-carrier-runtime.js');
const contactCenter=read('worker/src/contact-center-runtime.js');
const telecomNetwork=read('worker/src/magnanimous-telecom-network-runtime.js');
const providerEnv=read('worker/src/provider-runtime-env.js');
const agentDesk=read('frontend/app/agent-desk/page.tsx');

const checks=[];
const has=(source,text,label)=>checks.push([label,source.includes(text)]);
const lacks=(source,text,label)=>checks.push([label,!source.includes(text)]);

has(ports,'class CarrierBridge(Protocol)','carrier bridge uses an explicit dependency-inversion port');
has(container,'def build_container','telecom uses a composition root');
has(container,'AsteriskSipCarrierBridge(ari, resolved)','concrete carrier adapter is injected at the composition root');
has(calls,'class CallService','call business use-cases live outside HTTP routes');
has(monitoring,'class CarrierCallMonitor','monitor lifecycle is decomposed from call business logic');
has(adapter,'class AsteriskAriClient','ARI transport has one focused adapter');
has(adapter,'class AsteriskSipCarrierBridge','SIP carrier bridge is a replaceable adapter');
has(adapter,'"upstream_provider_exposed": False','external carrier identity stays beneath Magnanimous');
has(main,'Depends(get_container)','HTTP routes consume injected services');
lacks(main,'httpx','thin HTTP layer does not perform carrier/network transport');
lacks(main,'asyncio','thin HTTP layer does not own monitor lifecycle');
has(entrypoint,'PSTN_TRUNK_HOST','legacy PSTN configuration remains backward compatible');
has(entrypoint,'CARRIER_SIP_HOST','carrier-neutral configuration is supported');
has(dialplan,'@${CARRIER_SIP_ENDPOINT}','dialplan routes through replaceable carrier endpoint');
has(trunk,'[${CARRIER_SIP_ENDPOINT}]','SIP endpoint identity is configurable');
has(compose,'CARRIER_DIAL_CONTEXT','container configuration exposes the carrier bridge route');
has(phoneCarrier,'const carrierCore = await handleMagnanimousCarrierPhoneAlias(request, env);','ordinary-number routing checks the Magnanimous-owned carrier bridge before direct API fallbacks');
has(phoneCarrier,'if (plivoReady(env))','Plivo remains an optional low-cost direct fallback');
has(phoneCarrier,'if (!twilioReady(env)) return null;','Twilio remains an optional compatibility fallback rather than the primary route');
has(contactCenter,"primary_route:byoc?'owned-sip-core'","contact-center provider readiness prefers the owned SIP core when connected");
has(contactCenter,"path==='/api/contact-center/routing/recommend'&&request.method==='POST'",'skills routing has an executable tenant-scoped recommendation endpoint');
has(contactCenter,"async function recommendAgent",'skills routing uses native queue membership, availability and agent skills');
has(contactCenter,"skills_routing:true",'contact-center only advertises skills routing after the executable route exists');
has(contactCenter,"skills_routing:'operational'",'skills routing readiness is explicitly operational');
has(contactCenter,"path==='/api/contact-center/screen-pop'&&request.method==='GET'",'CRM screen pop has an executable tenant-scoped endpoint');
has(contactCenter,"async function crmScreenPop",'CRM screen pop resolves call/contact/email/phone context against the native CRM');
has(contactCenter,"crm_screen_pop:true",'contact-center only advertises CRM screen pop after the executable route exists');
has(contactCenter,"crm_screen_pop:'operational'",'CRM screen-pop readiness is explicitly operational');
has(agentDesk,"/api/contact-center/routing/recommend",'Agent Desk exposes skills-based routing to human agents');
has(agentDesk,"/api/contact-center/screen-pop",'Agent Desk exposes native CRM screen-pop lookup');
has(contactCenter,"recording:false",'contact-center does not claim full-call recording from voicemail recording alone');
has(contactCenter,"supervisor_audio:'specified-only'",'contact-center truthfully classifies supervisor audio as specified-only');
has(telecomNetwork,"provider_key:'magnanimous-owned-sip'",'owner telecom topology names the Magnanimous-owned SIP/PBX core as the preferred bridge');
has(telecomNetwork,"recommended_upstream:{provider_key:'telnyx'",'Telnyx is modeled as a replaceable recommended upstream');
has(telecomNetwork,"provider_key:'plivo'",'owner telecom topology exposes Plivo as a fallback option');
has(telecomNetwork,"provider_key:'twilio'",'owner telecom topology exposes Twilio as a compatibility fallback');
has(providerEnv,"'TELNYX_API_KEY'",'provider vault supports Telnyx credentials');
has(providerEnv,"'PLIVO_AUTH_ID'",'provider vault supports Plivo credentials');
has(providerEnv,"'TWILIO_ACCOUNT_SID'",'provider vault supports Twilio credentials');

const failed=checks.filter(([,ok])=>!ok);
for(const [label,ok] of checks)console.log(`${ok?'PASS':'FAIL'}: ${label}`);
if(failed.length){console.error(`\n${failed.length} telecom carrier bridge contract(s) failed.`);process.exit(1)}
console.log('\nMagnanimous Telecom carrier bridge + SOLID architecture lock passed.');
